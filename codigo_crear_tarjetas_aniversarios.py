# CALCULAR ANTIGÜEDAD (CORREGIDO)
# ======================================================
def calcular_antiguedad(fecha_ingreso_str):
    fecha_str = str(fecha_ingreso_str).strip()
    partes = fecha_str.split('/')

    if len(partes) == 3:
        try:
            mes_ingreso = int(partes[1])
            anio_ingreso = int(partes[2])

            hoy = datetime.now()

            # El aniversario a celebrar es el año actual menos el año en que ingresaron.
            anios = hoy.year - anio_ingreso

            # REGLA DE SEGURIDAD (Cambio de año):
            # Si generas las tarjetas en Diciembre para los de Enero, el año actual (hoy.year)
            # estará un año atrasado respecto al aniversario real. Por lo tanto, sumamos 1.
            if hoy.month == 12 and mes_ingreso == 1:
                anios += 1

            return max(0, anios)

        except ValueError:
            return 0

    return 0

