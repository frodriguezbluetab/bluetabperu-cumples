# SUBIR O ACTUALIZAR A GITHUB
# ======================================================
def subir_a_github(imagen_local_path, nombre_archivo_en_git):
    GITHUB_TOKEN = os.environ['GH_TOKEN']
    REPO = 'frodriguezbluetab/bluetabperu-cumples'
    RUTA_ARCHIVO = f'Aniversarios/{nombre_archivo_en_git}'
    API_URL = f'https://api.github.com/repos/{REPO}/contents/{RUTA_ARCHIVO}'

    with open(imagen_local_path, 'rb') as f:
        content = base64.b64encode(f.read()).decode('utf-8')

    headers = {
        'Authorization': f'token {GITHUB_TOKEN}',
        'Accept': 'application/vnd.github.v3+json'
    }

    resp = requests.get(API_URL, headers=headers)
    sha = resp.json().get("sha") if resp.status_code == 200 else None

    data = {
        "message": f"Actualización automática: {nombre_archivo_en_git}",
        "content": content,
        "branch": "main"
    }

    if sha:
        data["sha"] = sha

    r = requests.put(API_URL, headers=headers, json=data)
    if r.status_code in [200, 201]:
        print("🟣 Archivo subido/actualizado en GitHub")
        return f"https://github.com/{REPO}/blob/main/{RUTA_ARCHIVO}"

    print("❌ Error subiendo a GitHub:", r.text)
    return None


