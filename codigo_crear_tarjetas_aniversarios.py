def generar_imagen_por_genero(fila, output_name, antiguedad_str):
    slides_id_plantilla = '1cjW1qWkgB3p25rvrQnOzzzxhXExzNDAJuYuWokz11_k'
    slides_id_temporal = crear_copia_temporal(slides_id_plantilla)
    imagen_temp_drive_id = None

    nuevo_nombre = formatear_nombre_colaborador(fila['NOMBRE'].strip())

    try:
        fecha_aniversario = formatear_fecha(fila['Fecha de contratación'].strip())

        url_foto = fila['FOTO'].strip()
        match = re.search(r'/d/([a-zA-Z0-9_-]+)', url_foto)
        if not match:
            raise ValueError("No pude extraer ID de foto")

        image_id = match.group(1)
        url_publica = obtener_url_publica_drive(image_id)

        # Crea el archivo local 'imagen_546.png'
        procesar_imagen_drive(url_publica, "imagen_546.png")

        media = MediaFileUpload("imagen_546.png", mimetype="image/png")
        subida = drive_service.files().create(
            body={'name': 'imagen_546.png'},
            media_body=media,
            fields='id'
        ).execute()

        imagen_temp_drive_id = subida['id']
        imagen_final_url = obtener_url_publica_drive(imagen_temp_drive_id)

        time.sleep(3)

        presentation = slides_service.presentations().get(
            presentationId=slides_id_temporal
        ).execute()

        object_id_imagen = None
        for slide in presentation['slides']:
            for el in slide.get('pageElements', []):
                if el.get('image'):
                    object_id_imagen = el['objectId']
                    break
            if object_id_imagen:
                break

        if not object_id_imagen:
            raise ValueError("No hay imagen en la plantilla")

        slide_requests = [
            {
                'replaceAllText': {
                    'containsText': {'text': 'Nombre bluetaber', 'matchCase': True},
                    'replaceText': nuevo_nombre
                }
            },
            {
                'replaceAllText': {
                    'containsText': {'text': 'dia aniversario', 'matchCase': True},
                    'replaceText': fecha_aniversario
                }
            },
            {
                'replaceAllText': {
                    'containsText': {'text': 'X', 'matchCase': True},
                    'replaceText': antiguedad_str
                }
            },
            {
                'replaceImage': {
                    'imageObjectId': object_id_imagen,
                    'url': imagen_final_url
                }
            }
        ]

        exito = False
        for intento in range(3):
            try:
                slides_service.presentations().batchUpdate(
                    presentationId=slides_id_temporal,
                    body={'requests': slide_requests}
                ).execute()
                exito = True
                break
            except Exception as e:
                print(f"Intento {intento + 1} falló al contactar Slides. Esperando 5 seg...")
                time.sleep(5)

        if not exito:
            raise ValueError(f"Imposible procesar la tarjeta de {nuevo_nombre} después de 3 intentos.")

        request = drive_service.files().export_media(
            fileId=slides_id_temporal,
            mimeType='application/pdf'
        )
        fh = io.FileIO('temp_genero.pdf', 'wb')
        downloader = MediaIoBaseDownload(fh, request)

        done = False
        while not done:
            status, done = downloader.next_chunk()

        pages = convert_from_path('temp_genero.pdf', dpi=300)
        image_path = f"{output_name}.png"
        pages[0].save(image_path, 'PNG')

        return image_path

    finally:
        # ======================================================
        # BLOQUE FINALLY: Garantiza la eliminación pase lo que pase
        # ======================================================
        try:
            drive_service.files().delete(fileId=slides_id_temporal).execute()
        except Exception:
            pass # Falla silenciosamente si ya fue borrado o no existe

        if imagen_temp_drive_id:
            try:
                drive_service.files().delete(fileId=imagen_temp_drive_id).execute()
            except Exception:
                pass

        # Eliminar residuos locales del Colab
        if os.path.exists("imagen_546.png"):
            os.remove("imagen_546.png")

        if os.path.exists("temp_genero.pdf"):
            os.remove("temp_genero.pdf")


