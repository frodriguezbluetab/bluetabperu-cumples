# FORMATEAR FECHA ("DD/MM/YYYY" -> "DD de Mes")
# ======================================================
def formatear_fecha(fecha_str):
    meses = {
        1: "Enero", 2: "Febrero", 3: "Marzo", 4: "Abril",
        5: "Mayo", 6: "Junio", 7: "Julio", 8: "Agosto",
        9: "Septiembre", 10: "Octubre", 11: "Noviembre", 12: "Diciembre"
    }

    try:
        fecha_str = str(fecha_str).strip()
        partes = fecha_str.split('/')

        dia = partes[0]
        mes = int(partes[1])

        return f"{dia} de {meses[mes]}"
    except Exception as e:
        return fecha_str


# ======================================================
# FORMATEAR NOMBRE DE COLABORADOR
# ======================================================
def formatear_nombre_colaborador(nombre_completo):
    if not isinstance(nombre_completo, str) or not nombre_completo.strip():
        return ""

    conectores = {"DE", "DEL", "LA", "LAS", "LOS", "SAN", "MAC", "MC", "VAN", "VON"}
    palabras = nombre_completo.strip().upper().split()

    bloques = []
    bloque_actual = []

    for palabra in palabras:
        bloque_actual.append(palabra)
        if palabra not in conectores:
            bloques.append(" ".join(bloque_actual))
            bloque_actual = []

    if bloque_actual:
        bloques.append(" ".join(bloque_actual))

    if len(bloques) >= 2:
        apellidos = bloques[:2]
        nombres = bloques[2:]
    else:
        apellidos = bloques
        nombres = []

    nombre_invertido = " ".join(nombres + apellidos)
    return nombre_invertido.title()


