def obtener_url_publica_drive(file_id):
    try:
        drive_service.permissions().create(
            fileId=file_id,
            body={'type': 'anyone', 'role': 'reader'}
        ).execute()
    except Exception as e:
        print(f"ADVERTENCIA: No se pudo hacer pública la imagen. Error: {e}")
        print("Es probable que las políticas de tu Google Workspace no permitan compartir archivos públicamente.")

    return f"https://drive.google.com/uc?export=view&id={file_id}"


# ======================================================
# PROCESAR IMAGEN CON ESQUINAS REDONDEADAS
# ======================================================
def procesar_imagen_drive(image_url, output_path="imagen_546.png", size=(252, 250), radio=1):
    response = requests.get(image_url)
    img = Image.open(io.BytesIO(response.content)).convert("RGBA")

    img = img.resize(size, Image.LANCZOS)

    w, h = img.size
    mask = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(mask)
    draw.rounded_rectangle((0, 0, w, h), radius=radio, fill=255)
    img.putalpha(mask)

    img.save(output_path)
    return output_path


