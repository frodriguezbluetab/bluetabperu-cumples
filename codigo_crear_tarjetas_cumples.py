# PROCESAR IMAGEN (546x546 + esquinas redondeadas)
# ======================================================
def procesar_imagen_drive(image_url, output_path="imagen_546.png", size=(250, 250), radio=15):
    # 📥 Descarga la imagen desde la URL de Drive.
    response = requests.get(image_url)
    img = Image.open(io.BytesIO(response.content)).convert("RGBA")

    # 📐 Redimensiona la imagen y crea una máscara con esquinas redondeadas.
    img = img.resize(size, Image.LANCZOS)
    w, h = img.size
    mask = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(mask)
    draw.rounded_rectangle((0, 0, w, h), radius=radio, fill=255)

    # 🖼️ Aplica la máscara de redondeo a la imagen y la guarda localmente.
    img.putalpha(mask)
    img.save(output_path)
    return output_path

