# HACER ARCHIVO PÚBLICO EN DRIVE
# ======================================================
def obtener_url_publica_drive(file_id):
    # 🔓 Establece los permisos del archivo en Drive a 'lector' para 'cualquiera' (anyone).
    try:
        drive_service.permissions().create(
            fileId=file_id,
            body={'type': 'anyone', 'role': 'reader'}
        ).execute()
    except:
        pass
    # 🔗 Retorna la URL de descarga directa/visualización pública.
    return f"https://drive.google.com/uc?export=view&id={file_id}"

