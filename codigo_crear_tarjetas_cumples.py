# FORMATEAR NOMBRE DE COLABORADOR: INVIERTE ESTRUCTURA (Nombres y Apellidos) y comprende apellidos compuestos
# ======================================================
def formatear_nombre_colaborador(nombre_completo):
    if not isinstance(nombre_completo, str) or not nombre_completo.strip():
        return ""

    # 1. Definimos los conectores comunes en los apellidos hispanos
    conectores = {"DE", "DEL", "LA", "LAS", "LOS", "SAN", "MAC", "MC", "VAN", "VON"}

    # Limpiamos espacios extra y dividimos por cada espacio
    palabras = nombre_completo.strip().upper().split()

    bloques = []
    bloque_actual = []

    # 2. Agrupamos las palabras en bloques lógicos
    for palabra in palabras:
        bloque_actual.append(palabra)
        # Si la palabra NO es un conector, significa que el bloque (apellido/nombre) terminó
        if palabra not in conectores:
            bloques.append(" ".join(bloque_actual))
            bloque_actual = []

    # Por seguridad, si el string termina misteriosamente en un conector
    if bloque_actual:
        bloques.append(" ".join(bloque_actual))

    # 3. Identificamos Apellidos y Nombres
    if len(bloques) >= 2:
        apellidos = bloques[:2]
        nombres = bloques[2:]
    else:
        apellidos = bloques
        nombres = []

    # 4. Invertimos el orden (Nombres + Apellidos) y aplicamos Title Case
    nombre_invertido = " ".join(nombres + apellidos)

    # El método .title() capitaliza la primera letra de cada palabra
    return nombre_invertido.title()

