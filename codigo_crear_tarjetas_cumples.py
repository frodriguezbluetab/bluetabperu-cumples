# FORMATEAR FECHA ("DD/MM/YYYY" -> "DD de Mes")
# ======================================================
def formatear_fecha_cumple(fecha_str):
    # Diccionario con los nombres de los meses capitalizados
    meses = {
        1: "Enero", 2: "Febrero", 3: "Marzo", 4: "Abril",
        5: "Mayo", 6: "Junio", 7: "Julio", 8: "Agosto",
        9: "Setiembre", 10: "Octubre", 11: "Noviembre", 12: "Diciembre"
    }

    try:
        fecha_str = str(fecha_str).strip()
        partes = fecha_str.split('/')

        # Al convertir a int, eliminamos automáticamente ceros a la izquierda (ej. '04' -> 4)
        dia = partes[0]
        mes = int(partes[1])

        # Retornamos el formato (DD de Mes)
        return f"{dia} de {meses[mes]}"
    except Exception as e:
        return fecha_str


