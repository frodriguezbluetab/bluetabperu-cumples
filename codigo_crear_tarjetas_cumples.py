# SUBIR A GITHUB
# ======================================================
def subir_a_github(imagen_local_path, nombre_archivo_en_git):
    GITHUB_TOKEN = os.environ['GH_TOKEN']
    REPO = 'frodriguezbluetab/bluetabperu-cumples'
    RUTA_ARCHIVO = f'Tarjetas_Cumples/{nombre_archivo_en_git}'
    API_URL = f'https://api.github.com/repos/{REPO}/contents/{RUTA_ARCHIVO}'

    # 📄 Codifica la imagen local a Base64 para el API de GitHub.
    with open(imagen_local_path, 'rb') as img_file:
        content = base64.b64encode(img_file.read()).decode('utf-8')

    # 🔑 Define las cabeceras con el Token de autenticación.
    headers = {
        'Authorization': f'token {GITHUB_TOKEN}',
        'Accept': 'application/vnd.github.v3+json'
    }

    # 🔄 Verifica si el archivo ya existe para obtener el SHA (necesario para actualizar).
    response = requests.get(API_URL, headers=headers)
    sha = response.json().get('sha') if response.status_code == 200 else None

    # 📤 Crea el payload de la petición (PUT) para subir o actualizar.
    data = {
        'message': f"{nombre_archivo_en_git}",
        'content': content,
        'branch': 'main'
    }
    if sha:
        data['sha'] = sha # Agrega el SHA para actualizar el archivo existente.
    r = requests.put(API_URL, headers=headers, json=data)

    # ✅ Retorna la URL si la subida fue exitosa.
    if r.status_code in [200, 201]:
        return f"https://github.com/{REPO}/blob/main/{RUTA_ARCHIVO}"
    return None

